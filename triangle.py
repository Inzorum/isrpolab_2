def area(a, h): 
    ''' Принимает сторону треугольника и высоту треугольника (переменные a, h) и возвращает его площадь (a * h / 2) '''
    return a * h / 2 

def perimeter(a, b, c): 
    ''' Принимает стороны треугоьника (переменные a,b,c) и возвращает его периметр (a + b + c ) '''
    return a + b + c 
