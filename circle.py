import math


def area(r):
    '''
    Принимает число r, возвращает площадь круга радиуса r
    Например, для числа 3 будет возвращено число 28.274333882308138
    '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает число r, возвращает площадь круга радиуса r
    Например, для числа 3 будет возвращено число 18.84955592153876
    '''
    return 2 * math.pi * r
